/** 渲染某个页面的说明（没有配置就什么都不输出）。 */
function help_html(string $page): string
{
    $map = help_map();
    if (!isset($map[$page])) {
        return '';
    }
    [$what, $steps, $done, $note] = $map[$page];
    $topic = guide_topic_of($page);
    $h = '<details class="page-help"><summary>'
        . '<span class="ph-mark">?</span>'
        . '<span class="ph-q">' . e(t($what)) . '</span>'
        . '<span class="ph-toggle">' . e(t('使用说明')) . '</span></summary>'
        . '<div class="ph-body">'
        . '<div class="ph-section"><strong>' . e(t('新手照着做')) . '</strong>'
        . '<ol class="ph-steps">';
    foreach ($steps as $step) {
        $h .= '<li>' . e(t($step)) . '</li>';
    }
    $h .= '</ol></div>'
        . '<div class="ph-section ph-result"><strong>' . e(t('完成后检查')) . '</strong>'
        . '<p>' . e(t($done)) . '</p></div>'
        . '<div class="ph-section ph-note"><strong>' . e(t('注意事项')) . '</strong>'
        . '<p>' . e(t($note)) . '</p></div>';
    if ($topic !== null) {
        $h .= '<a class="ph-guide" href="?p=guide&topic=' . e($topic) . '">'
            . e(t('打开这个模块的完整使用说明 →')) . '</a>';
    }
    return $h . '</div></details>';
}


/** 页面 → 属于哪个模块的说明书。 */
function guide_topic_of(string $page): ?string
{
    $sales = ['invoices', 'invoice-new', 'invoice-view', 'quotes', 'credit-notes',
              'customers', 'receipts', 'sales-orders', 'recurring-invoices', 'delivery-notes'];
    $purchase = ['bills', 'bill-new', 'bill-view', 'expenses', 'expense-new', 'vendors',
                 'payments', 'purchase-orders', 'recurring-bills'];
    $bank = ['banks', 'bank-transactions', 'bank-import', 'reconcile', 'bank-rules', 'bank-transfer'];
    $accounting = ['accounts', 'journal', 'journal-new', 'rates', 'opening-balances',
                   'period-close', 'pending', 'pending-rec', 'settle', 'revalue', 'locks'];
    $reports = ['report-center', 'report-statements', 'report-tb', 'report-pnl', 'report-bs',
                'report-cf', 'report-gl', 'report-aging', 'report-bank', 'report-daybook',
                'report-sales', 'report-purchase', 'report-ratios', 'report-fx', 'report-tax',
                'report-account-types', 'report-gl-detail', 'report-customer-balance',
                'report-vendor-balance', 'tax'];
    if (in_array($page, $sales, true)) { return 'sales'; }
    if (in_array($page, $purchase, true)) { return 'purchase'; }
    if (in_array($page, $bank, true)) { return 'bank'; }
    if (in_array($page, $accounting, true)) { return 'accounting'; }
    if (in_array($page, $reports, true)) { return 'reports'; }
    return null;
}
