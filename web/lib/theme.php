const THEME_DEFAULT = 'tech';

function theme_current(): string
{
    $t = (string) ($_COOKIE['ledu_theme'] ?? THEME_DEFAULT);
    return array_key_exists($t, theme_presets()) ? $t : THEME_DEFAULT;
}

/** 主题覆盖的 CSS（当前主题没有覆盖时返回空串）。 */
function theme_css(): string
{
    $t = theme_current();
    $preset = theme_presets()[$t];
    $vars = $preset['vars'] ?? [];
    if (!$vars) {
        return '';
    }
    $css = ':root{color-scheme:' . (($preset['mode'] ?? 'light') === 'dark' ? 'dark' : 'light') . ';';
    foreach ($vars as $k => $v) {
        $css .= $k . ':' . $v . ';';
    }
    return $css . '}';
}
